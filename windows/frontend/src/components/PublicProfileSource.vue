<script setup lang="ts">
import { computed, onBeforeUnmount, ref, watch } from 'vue'
import { api, hasPublicProfileSource, hasDeliveredExport } from '../api/backend'
import { uiFailure } from '../api/failureMessages'
import type { DeliveredExportResult, OnboardingPreview, PublicProfileMode, PublicProfileRoute, PublicProfileSourcePreview } from '../api/contract'
import { usePreviewExpiry } from '../composables/previewExpiry'
import { useProfileActions } from '../composables/profileActions'

const emit = defineEmits<{ changed: [] }>()
const actions = useProfileActions()
const { blocked } = actions
const available = computed(hasPublicProfileSource)
const exportAvailable = computed(hasDeliveredExport)
const purpose = ref<'import' | 'export'>('import')
const repository = ref('')
const target = ref('')
const route = ref<PublicProfileRoute>('protected')
const mode = ref<PublicProfileMode>('profile')
const root = ref('')
const initialPolicy = ref('')
const directConsent = ref(false)
const targetApproval = ref('')
const phase = ref<'idle' | 'fetching' | 'applying' | 'exporting' | 'saving'>('idle')
const error = ref('')
const attempted = ref(false)
const receipt = ref<PublicProfileSourcePreview | null>(null)
const done = ref<OnboardingPreview | null>(null)
const exportPass = ref('')
const exported = ref<DeliveredExportResult | null>(null)
const savedPath = ref('')
const { expired, arm: armExpiry, clear: clearExpiry, check: checkExpiry } = usePreviewExpiry(() => { targetApproval.value = ''; exportPass.value = ''; cancelOwned() })
const needsRoot = computed(() => purpose.value === 'import' && (mode.value === 'enroll' || mode.value === 'epoch_enroll'))
const needsTarget = computed(() => purpose.value === 'import' && ['recover', 'epoch_recover', 'epoch_enroll'].includes(mode.value))
const canApply = computed(() => !actions.busy.value && receipt.value?.purpose === 'import' && phase.value === 'idle' && !expired.value && !receipt.value.profile.wouldDowngrade && (!needsTarget.value || targetApproval.value === receipt.value.profile.targetSHA256))
let generation = 0
let ownedRequest = ''
let mounted = true

function cancelOwned(): void {
  const id = ownedRequest
  ownedRequest = ''
  if (id && (phase.value === 'idle' || phase.value === 'fetching')) void api.cancelPublicProfileSource(id).catch(() => {})
}
function invalidate(): void {
  generation++
  clearExpiry()
  cancelOwned()
  receipt.value = null
  done.value = null
  exported.value = null
  savedPath.value = ''
  exportPass.value = ''
  error.value = ''
  targetApproval.value = ''
  attempted.value = false
}
watch([repository, target, route, mode, root, initialPolicy, directConsent, purpose], invalidate, { flush: 'sync' })
watch(route, () => { directConsent.value = false }, { flush: 'sync' })
watch(actions.revision, () => { if (!actions.ownsPending.value) invalidate() }, { flush: 'sync' })
onBeforeUnmount(() => {
  mounted = false; generation++; clearExpiry(); cancelOwned()
  exportPass.value = ''; exported.value = null; savedPath.value = ''; receipt.value = null; done.value = null; targetApproval.value = ''
})
function owned(current: number): boolean { return mounted && actions.current() && current === generation }

async function preview(): Promise<void> {
  if (!available.value || actions.busy.value || phase.value !== 'idle' || !actions.current()) return
  attempted.value = true
  error.value = ''
  if (!repository.value || !target.value || needsRoot.value && (!/^[a-f0-9]{64}$/.test(root.value) || !/^[a-f0-9]{64}$/.test(initialPolicy.value))) {
    error.value = 'Укажите адрес и путь профиля. Для первой установки нужны независимо полученные SHA256 root.json и списка отзывов.'
    return
  }
  if (route.value === 'bootstrap' && !directConsent.value) {
    error.value = 'Подтвердите загрузку публичного профиля без VPN или выберите другой маршрут.'
    return
  }
  const original = actions.begin('profile_preview')
  if (!original) return
  cancelOwned()
  receipt.value = null
  done.value = null
  targetApproval.value = ''
  clearExpiry()
  const current = ++generation
  // Correlation only; authorization nonce is generated by Go, never Math.random.
  const requestId = `public-${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`
  ownedRequest = requestId
  phase.value = 'fetching'
  try {
    const result = await api.previewPublicProfileSource({
      request_id: requestId,
      purpose: purpose.value,
      source: { repository: repository.value, target_path: target.value, route: route.value, allow_direct: route.value === 'bootstrap' && directConsent.value },
      import: { json: '', mode: purpose.value === 'export' ? 'profile' : mode.value, approved_root_sha256: needsRoot.value ? root.value : '', approved_pin_policy_sha256: needsRoot.value ? initialPolicy.value : '' },
    })
    const accepted = owned(current) && original.current() && ownedRequest === requestId
    original.received(accepted)
    if (accepted) { receipt.value = result; armExpiry(result.expiresAt) }
  } catch (failure) {
    const message = original.failed(failure)
    if (owned(current)) {
      receipt.value = null
      clearExpiry()
      error.value = message
      cancelOwned()
    }
  } finally {
    if (mounted) phase.value = 'idle'
    original.finish()
  }
}

async function apply(): Promise<void> {
  const currentReceipt = receipt.value
  if (!canApply.value || !currentReceipt) return
  if (checkExpiry()) return
  const original = actions.begin('profile_apply')
  if (!original) return
  const current = generation
  clearExpiry()
  phase.value = 'applying'
  error.value = ''
  receipt.value = null // one use, including a failed apply
  try {
    const result = await api.applyPublicProfileSource(currentReceipt.token, needsTarget.value ? targetApproval.value : '')
    original.received(false)
    if ((currentReceipt.profile.targetSHA256 && result.targetSHA256 !== currentReceipt.profile.targetSHA256) || (currentReceipt.profile.bundleIdentity && result.bundleIdentity !== currentReceipt.profile.bundleIdentity)) {
      if (owned(current)) error.value = original.failed(undefined)
      return
    }
    const accepted = owned(current) && original.current()
    original.received(accepted)
    if (accepted) done.value = result
  } catch (failure) {
    const message = original.failed(failure)
    if (owned(current)) error.value = message
  } finally {
    if (mounted) { phase.value = 'idle'; ownedRequest = ''; emit('changed') }
    original.finish()
  }
}

async function exportTransfer(): Promise<void> {
  const selected = receipt.value
  if (!exportAvailable.value || actions.busy.value || selected?.purpose !== 'export' || phase.value !== 'idle' || expired.value || exportPass.value.length < 8) return
  if (checkExpiry()) return
  const original = actions.begin('transfer_export')
  if (!original) return
  const current = generation
  clearExpiry()
  const password = exportPass.value
  exportPass.value = ''
  receipt.value = null
  phase.value = 'exporting'
  error.value = ''
  exported.value = null
  savedPath.value = '' // a new export cannot display the previous attempt as its result
  try {
    const result = await api.exportPublicProfileSource(selected.token, password)
    original.received(false)
    if (result.destinationRootSHA256 !== selected.destinationRootSHA256 || result.destinationPinPolicySHA256 !== selected.destinationPinPolicySHA256 || result.targetSHA256 !== selected.profile.targetSHA256 || result.profileIdentity !== selected.profile.bundleIdentity) {
      if (owned(current)) error.value = uiFailure.profileExportMismatch
      return
    }
    const accepted = owned(current) && original.current()
    original.received(accepted)
    if (accepted) exported.value = result
  } catch (failure) {
    const message = original.failed(failure)
    if (owned(current)) error.value = message
  } finally {
    if (mounted) { phase.value = 'idle'; exportPass.value = ''; ownedRequest = ''; emit('changed') }
    original.finish()
  }
}

async function saveTransfer(): Promise<void> {
  const selected = exported.value
  if (!selected || actions.busy.value || phase.value !== 'idle') return
  const original = actions.begin('transfer_save')
  if (!original) return
  const current = generation
  phase.value = 'saving'
  error.value = ''
  savedPath.value = '' // a previous successful save is not the outcome of this attempt
  try {
    const path = await api.saveProtectedProfileTransfer(selected.transport)
    const accepted = owned(current) && original.current() && exported.value === selected
    if (path === '') original.cancelled()
    else original.received(accepted)
    if (accepted) savedPath.value = path
  } catch (failure) {
    const message = original.failed(failure)
    if (owned(current)) error.value = message
  } finally { if (mounted) phase.value = 'idle'; original.finish() }
}
</script>

<template>
  <section class="public-source" aria-labelledby="public-source-title">
    <h2 id="public-source-title">Публичный профиль</h2>
    <p class="muted">Получите подписанные настройки из своего источника. Пароли и значения секретов в таком пакете не передаются.</p>
    <p v-if="!available" class="muted" role="status">Получение публичных профилей недоступно в этой версии приложения.</p>
    <form class="source-fields" novalidate :aria-busy="phase !== 'idle'" @submit.prevent="preview">
      <fieldset :disabled="blocked || !available || phase !== 'idle' && phase !== 'fetching'">
        <legend class="sr-title">Источник и способ применения</legend>
        <label for="public-purpose">Назначение</label>
        <select id="public-purpose" v-model="purpose">
          <option value="import">Применить на этом ПК</option>
          <option value="export" :disabled="!exportAvailable">Перенести установленный профиль на новое устройство</option>
        </select>
        <label for="public-repository">Адрес репозитория</label>
        <input id="public-repository" v-model.trim="repository" type="url" autocomplete="off" spellcheck="false" :aria-invalid="attempted && !repository || undefined" aria-describedby="public-source-help" />
        <label for="public-target">Путь профиля</label>
        <input id="public-target" v-model.trim="target" autocomplete="off" spellcheck="false" :aria-invalid="attempted && !target || undefined" aria-describedby="public-source-help" />
        <p id="public-source-help" class="muted">Адрес и точный путь профиля получите у администратора. Источник не назначает себе доверие автоматически.</p>
        <label for="public-route">Маршрут загрузки</label>
        <select id="public-route" v-model="route">
          <option value="protected">Через текущее VPN-подключение</option>
          <option value="bootstrap">Без VPN — только публичный профиль</option>
          <option value="local">Локальный репозиторий на этом ПК</option>
        </select>
        <label v-if="route === 'bootstrap'" class="consent"><input v-model="directConsent" type="checkbox" /> Разрешаю обратиться к этому источнику без VPN для загрузки открытого профиля</label>
        <label v-if="purpose === 'import'" for="public-mode">Действие</label>
        <select v-if="purpose === 'import'" id="public-mode" v-model="mode">
          <option value="profile">Обновить профиль</option>
          <option value="enroll">Первая установка</option>
          <option value="recover">Восстановить профиль</option>
          <option value="epoch_recover">Восстановить после смены ключа издателя</option>
          <option value="epoch_enroll">Первая установка с новым ключом издателя</option>
        </select>
        <template v-if="needsRoot">
          <label for="public-root">SHA256 корневого документа root.json из независимого источника</label>
          <input id="public-root" v-model.trim="root" autocomplete="off" spellcheck="false" :aria-invalid="attempted && !/^[a-f0-9]{64}$/.test(root) || undefined" aria-describedby="public-root-help" />
          <p id="public-root-help" class="muted">Сверьте оба отпечатка с администратором по отдельному доверенному каналу. Не берите подтверждение из загружаемого пакета.</p>
          <label for="public-initial-policy">SHA256 первого списка отзывов из независимого источника</label>
          <input id="public-initial-policy" v-model.trim="initialPolicy" autocomplete="off" spellcheck="false" :aria-invalid="attempted && !/^[a-f0-9]{64}$/.test(initialPolicy) || undefined" aria-describedby="public-policy-help" />
          <p id="public-policy-help" class="muted">Этот список задаёт известные запреты для нового ПК. Если отпечаток не совпал, запросите у администратора новый комплект и независимую сверку.</p>
        </template>
        <div class="actions">
          <button class="btn" type="submit" :disabled="blocked || phase !== 'idle'">Получить и проверить</button>
          <button v-if="phase === 'fetching'" class="btn" type="button" @click="invalidate">Отменить получение</button>
        </div>
      </fieldset>
    </form>
    <p v-if="phase === 'fetching'" class="muted" role="status">Получаем пакет и проверяем подписи, доверие и доступность необходимых секретов…</p>
    <p v-if="phase === 'applying'" class="muted" role="status">Повторная проверка и применение профиля…</p>
    <p v-if="phase === 'exporting'" class="muted" role="status">Проверяем установленный профиль и создаём зашифрованный перенос…</p>
    <p v-if="phase === 'saving'" class="muted" role="status">Выберите файл для зашифрованного переноса…</p>
    <p v-if="error" class="source-error" role="alert">{{ error }}</p>
    <div v-if="receipt" class="source-preview">
      <h3>{{ receipt.purpose === 'export' ? 'Установленный профиль подготовлен к переносу' : 'Профиль проверен для подтверждения' }}</h3>
      <p v-if="expired" class="source-error" role="status">Срок превью истёк. Получите новое перед подтверждением.</p>
      <dl>
        <dt>Каналов</dt><dd>{{ receipt.profile.channels }}</dd>
        <dt>Версия профиля</dt><dd>{{ receipt.profile.bundleIdentity || 'Не отображается' }}</dd>
        <dt>Текущая версия</dt><dd>{{ receipt.profile.currentIdentity || 'Не отображается' }}</dd>
        <dt>Издатель</dt><dd class="mono">{{ receipt.profile.signerFingerprint || 'Нет данных' }}</dd>
        <dt>Цепочка доставки</dt><dd class="mono">{{ receipt.profile.deliveryAnchorSHA256 || 'Нет данных' }}</dd>
        <template v-if="receipt.profile.bootstrapPolicySHA256"><dt>Подтверждённый первый список отзывов</dt><dd class="mono">{{ receipt.profile.bootstrapPolicySHA256 }}</dd></template>
        <dt>Подтвердить до</dt><dd>{{ receipt.expiresAt }}</dd>
      </dl>
      <template v-if="receipt.purpose === 'export'">
        <p class="muted">На новом устройстве выберите первую установку. Этот SHA256 документа root.json сверяется там отдельно:</p>
        <p class="mono hash">{{ receipt.destinationRootSHA256 }}</p>
        <p class="muted">Список отзывов для нового ПК также сверяется отдельно с получателем:</p>
        <p class="mono hash">{{ receipt.destinationPinPolicySHA256 }}</p>
        <label for="public-export-pass">Парольная фраза переноса</label>
        <input id="public-export-pass" v-model="exportPass" type="password" autocomplete="new-password" :disabled="blocked || expired || phase !== 'idle'" />
        <p class="muted">Будут зашифрованы только секреты, необходимые используемым каналам профиля. Передайте пароль отдельно от файла.</p>
        <button class="btn primary" type="button" :disabled="blocked || phase !== 'idle' || expired || exportPass.length < 8" @click="exportTransfer">Создать зашифрованный перенос</button>
      </template>
      <template v-else>
      <p class="muted">Сверьте издателя и ожидаемую версию. При применении все проверки выполнятся повторно.</p>
      <label v-if="needsTarget" for="public-target-approval">Подтвердите SHA256 профиля: <span class="mono hash">{{ receipt.profile.targetSHA256 }}</span></label>
      <input v-if="needsTarget" id="public-target-approval" v-model.trim="targetApproval" autocomplete="off" spellcheck="false" aria-describedby="public-approval-help" :disabled="blocked || expired || phase !== 'idle'" />
      <p v-if="needsTarget" id="public-approval-help" class="muted">Введите или вставьте сверенный отпечаток. Изменение ключей и восстановление требуют отдельного подтверждения.</p>
      <button class="btn primary" type="button" :disabled="!canApply" @click="apply">Применить этот профиль</button>
      </template>
    </div>
    <div v-if="exported" class="source-preview">
      <h3>Зашифрованный перенос создан</h3>
      <p class="muted">Профиль {{ exported.profileIdentity }}, секретов — {{ exported.secrets }}. Сохраните файл; на новом устройстве всё проверится повторно.</p>
      <p class="mono hash">SHA256 root.json: {{ exported.destinationRootSHA256 }}</p>
      <p class="mono hash">SHA256 списка отзывов: {{ exported.destinationPinPolicySHA256 }}</p>
      <p class="mono hash">SHA256 профиля: {{ exported.targetSHA256 }}</p>
      <p class="muted">На новом устройстве выберите «{{ exported.destinationMode === 'epoch_enroll' ? 'Первая установка с новым ключом издателя' : 'Первая установка' }}» и сверяйте отпечатки с этим устройством.</p>
      <p class="muted">Это установка проверенного профиля на чистое устройство. История доверия уже настроенного устройства не сбрасывается и не клонируется из файла.</p>
      <button class="btn" type="button" :disabled="blocked || phase !== 'idle'" @click="saveTransfer">Сохранить зашифрованный файл…</button>
      <p v-if="savedPath" class="muted">Сохранено: {{ savedPath }}</p>
    </div>
    <p v-if="done" class="source-done" role="status">Получен ответ на применение профиля {{ done.bundleIdentity || 'выбранной версии' }}. Перечитайте принятую версию; готовность подключения отображается отдельно в состоянии приложения.</p>
  </section>
</template>

